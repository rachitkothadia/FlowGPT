#!/usr/bin/env python3
"""Generate native lookup tables from the pinned, vendored Unicode CLDR data."""
import json, pathlib, collections, sys
root=pathlib.Path(__file__).resolve().parent.parent
data=json.loads((root/'Shared/Data/currencies.json').read_text())
aliases=collections.defaultdict(set)
records=data['currencies'];narrow=collections.Counter(x['narrow'] for x in records.values())
symbols={}
for code,row in sorted(records.items()):
 symbol=row['symbol']
 if symbol==code and row['narrow']!=code and narrow[row['narrow']]==1: symbol=row['narrow']
 symbols[code]=symbol
 for alias in row['aliases']:
  if code in {'XXX','XAU','XAG','XPT','XPD'} and alias!=code:continue
  for variant in (alias,alias.lower(),alias.upper(),alias.title(),alias.capitalize()):
   aliases[variant.translate(str.maketrans('ABCDEFGHIJKLMNOPQRSTUVWXYZ','abcdefghijklmnopqrstuvwxyz'))].add(code)
# Ordinary family names with standard family symbols. No country inference for dollars.
common={'rupee':'INR','rupees':'INR','रुपये':'INR','रुपए':'INR','रुपया':'INR','रुपयां':'INR','रुपयांचा':'INR','रुपयांचे':'INR','રૂપિયા':'INR','डॉलर':'USD','डॉलर्स':'USD','यूरो':'EUR','युरो':'EUR','dollar':'USD','dollars':'USD','euro':'EUR','euros':'EUR','pound':'GBP','pounds':'GBP','yen':'JPY','yuan':'CNY','US dollars':'USD','Canadian dollars':'CAD','Australian dollars':'AUD','Japanese yen':'JPY','South Korean won':'KRW'}
for alias,code in common.items():aliases[alias.lower()]={code}
def quote(x):return json.dumps(x,ensure_ascii=False)
lines=['// Generated by Scripts/currency-data.py; Unicode CLDR '+data['cldrVersion']+'. See Data/UNICODE-LICENSE.txt.', '#pragma once','#include <unordered_map>','#include <string>','namespace flow_format {','struct CurrencyAlias {const char* name;const char* symbol;};','inline constexpr CurrencyAlias rawCurrencyAliases[]={']
for alias,codes in sorted(aliases.items()):
 if len(codes)!=1:continue
 code=next(iter(codes));lines.append('{'+quote(alias)+','+quote(symbols[code])+'},')
lines+=['};','inline const std::unordered_map<std::string,std::string>& currencyAliases(){','static const auto data=[] {std::unordered_map<std::string,std::string> result;result.reserve(sizeof(rawCurrencyAliases)/sizeof(rawCurrencyAliases[0]));for(const auto& entry:rawCurrencyAliases)result.emplace(entry.name,entry.symbol);return result;}();return data;}','inline const std::unordered_map<std::string,std::string>& currencyCodes(){','static const std::unordered_map<std::string,std::string> data={']
for code,symbol in sorted(symbols.items()):lines.append('{'+quote(code)+','+quote(symbol)+'},')
lines+=['};return data;}','}']
header='\n'.join(lines)+'\n';p=root/'Shared/CurrencyData.h'
if '--write' in sys.argv:p.write_text(header)
elif p.read_text()!=header:raise SystemExit('Currency table is stale')
print(json.dumps({'currencies':len(records),'aliases':sum(len(v)==1 for v in aliases.values()),'locales':len(data['locales']),'source_commit':data['commit']}))
